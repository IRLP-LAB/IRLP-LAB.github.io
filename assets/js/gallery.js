/* ================= STATE ================= */
let currentImages = [];
let currentIndex = 0;

/* ================= ELEMENTS ================= */
const folderGrid = document.getElementById("folderGrid");
const imageGrid = document.getElementById("imageGrid");
const backBtn = document.getElementById("backBtn");
const sectionTitle = document.getElementById("sectionTitle");
const zoomOverlay = document.getElementById("zoomOverlay");
const zoomedImage = document.getElementById("zoomedImage");

/* ================= EVENT LISTENERS ================= */
document.querySelector('.zoom-prev').addEventListener('click', prevImage);
document.querySelector('.zoom-next').addEventListener('click', nextImage);
document.querySelector('.close-btn').addEventListener('click', closeZoom);

/* ================= FUNCTIONS ================= */
function openFolder(title, key) {
  if (!galleryData[key]) {
    console.error("Invalid gallery key:", key);
    return;
  }

  currentImages = galleryData[key];
  currentIndex = 0;

  folderGrid.style.display = "none";
  imageGrid.style.display = "grid";
  backBtn.style.display = "flex";
  sectionTitle.style.display = "block";
  sectionTitle.textContent = title;

  imageGrid.innerHTML = "";

  currentImages.forEach((src, index) => {
    const div = document.createElement("div");
    div.className = "gallery-item";
    div.innerHTML = `<img src="${src}" onclick="zoomImage(${index})">`;
    imageGrid.appendChild(div);
  });
}

function goBack() {
  folderGrid.style.display = "grid";
  imageGrid.style.display = "none";
  backBtn.style.display = "none";
  sectionTitle.style.display = "none";
}

function zoomImage(index) {
  currentIndex = index;
  zoomedImage.src = currentImages[currentIndex];
  zoomOverlay.classList.add("active");
}

function closeZoom() {
  zoomOverlay.classList.remove("active");
}

function nextImage() {
  currentIndex = (currentIndex + 1) % currentImages.length;
  zoomedImage.src = currentImages[currentIndex];
}

function prevImage() {
  currentIndex = (currentIndex - 1 + currentImages.length) % currentImages.length;
  zoomedImage.src = currentImages[currentIndex];
}


